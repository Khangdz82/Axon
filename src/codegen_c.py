# Aether C23 Backend Code Generator
from typing import Dict, List, Optional
from src.ast_nodes import (
    Program, StructDef, FieldDef, FuncDef, Param, TypeNode,
    Statement, LetStmt, AssignStmt, ForStmt, ReturnStmt, ExprStmt,
    Expr, BinaryExpr, NumberLiteral, Identifier, FieldAccess,
    CallExpr, MethodCallExpr, SpawnExpr
)

C_TYPE_MAP = {
    "f32": "float",
    "f64": "double",
    "i32": "int32_t",
    "i64": "int64_t",
    "u32": "uint32_t",
    "u64": "uint64_t",
    "bool": "bool",
    "void": "void"
}

class CCodeGen:
    def __init__(self, program: Program):
        self.program = program
        self.structs: Dict[str, StructDef] = {s.name: s for s in program.structs}
        self.functions: Dict[str, FuncDef] = {f.name: f for f in program.functions}
        self.out_lines: List[str] = []
        self.helper_defs: List[str] = []
        self.task_counter = 0

    def generate(self) -> str:
        self.out_lines = [
            "// Auto-generated by Aether Compiler - Native SoA + Zero Lifetime + Colorless Fibers",
            "#define _CRT_SECURE_NO_WARNINGS",
            '#include "aether_runtime.h"',
            ""
        ]

        # 1. Forward declare struct and SoA Table definitions
        for s in self.program.structs:
            self._gen_table_typedef(s)

        # 2. Forward declare functions
        for f in self.program.functions:
            self._gen_func_forward_decl(f)
        self.out_lines.append("")

        # 3. Generate function implementations
        func_bodies = []
        for f in self.program.functions:
            func_bodies.append(self._gen_func(f))

        # Insert any task helpers before the functions
        full_code = self.out_lines + self.helper_defs + [""] + func_bodies
        return "\n".join(full_code)

    def _c_type(self, type_node: Optional[TypeNode]) -> str:
        if not type_node:
            return "void"
        if type_node.is_table:
            return f"Aether_Table_{type_node.elem_type}"
        return C_TYPE_MAP.get(type_node.name, type_node.name)

    def _gen_table_typedef(self, s: StructDef):
        table_name = f"Aether_Table_{s.name}"
        lines = [
            f"// Native Structure of Arrays (SoA) for {s.name}",
            f"typedef struct {table_name} {{",
            "    size_t count;",
            "    size_t capacity;"
        ]
        for field in s.fields:
            c_ftype = C_TYPE_MAP.get(field.type_name, field.type_name)
            lines.append(f"    {c_ftype}* AETHER_RESTRICT {field.name};")
        lines.append(f"}} {table_name};")
        lines.append("")

        # Constructor
        lines.append(f"static inline {table_name} {table_name}_create(size_t capacity) {{")
        lines.append(f"    {table_name} t;")
        lines.append("    t.count = capacity;")
        lines.append("    t.capacity = capacity;")
        for field in s.fields:
            c_ftype = C_TYPE_MAP.get(field.type_name, field.type_name)
            lines.append(f"    t.{field.name} = ({c_ftype}*)AETHER_ALIGN_ALLOC(capacity * sizeof({c_ftype}), AETHER_CACHE_LINE);")
        lines.append("    return t;")
        lines.append("}")
        lines.append("")

        # Destructor
        lines.append(f"static inline void {table_name}_free({table_name}* t) {{")
        lines.append("    if (!t) return;")
        for field in s.fields:
            lines.append(f"    if (t->{field.name}) AETHER_ALIGN_FREE(t->{field.name});")
            lines.append(f"    t->{field.name} = NULL;")
        lines.append("    t->count = t->capacity = 0;")
        lines.append("}")
        lines.append("")

        self.out_lines.extend(lines)

    def _gen_func_forward_decl(self, f: FuncDef):
        if f.name == "main":
            return
        ret_type = self._c_type(f.return_type)
        param_strs = []
        for p in f.params:
            ptype = self._c_type(p.type_node)
            if p.type_node and p.type_node.is_table and p.intent in {"mut", "let"}:
                param_strs.append(f"{ptype}* {p.name}")
            else:
                param_strs.append(f"{ptype} {p.name}")
        params_str = ", ".join(param_strs) if param_strs else "void"
        self.out_lines.append(f"{ret_type} {f.name}({params_str});")

    def _gen_func(self, f: FuncDef) -> str:
        ret_type = self._c_type(f.return_type)
        if f.name == "main":
            ret_type = "int"
            params_str = "void"
        else:
            param_strs = []
            for p in f.params:
                ptype = self._c_type(p.type_node)
                if p.type_node and p.type_node.is_table and p.intent in {"mut", "let"}:
                    param_strs.append(f"{ptype}* {p.name}")
                else:
                    param_strs.append(f"{ptype} {p.name}")
            params_str = ", ".join(param_strs) if param_strs else "void"

        ctx = {
            "params": {p.name: p for p in f.params},
            "vars": {},
            "active_loops": [],
            "ret_type": ret_type
        }

        body_lines = []
        for stmt in f.body:
            body_lines.extend(self._gen_stmt(stmt, ctx, indent="    "))

        if f.name == "main" and not any(isinstance(s, ReturnStmt) for s in f.body):
            body_lines.append("    return 0;")

        lines = [f"{ret_type} {f.name}({params_str}) {{"]
        lines.extend(body_lines)
        lines.append("}")
        return "\n".join(lines)

    def _gen_stmt(self, stmt: Statement, ctx: dict, indent: str = "    ") -> List[str]:
        lines = []
        if isinstance(stmt, LetStmt):
            expr_code, pre_stmts = self._gen_expr(stmt.expr, ctx, indent)
            for p in pre_stmts:
                lines.append(f"{indent}{p}" if not p.startswith(indent) else p)
            c_type = self._c_type(stmt.type_node) if stmt.type_node else "auto"
            if c_type == "auto":
                if isinstance(stmt.expr, SpawnExpr):
                    c_type = "Aether_Worker*"
                elif isinstance(stmt.expr, CallExpr):
                    if stmt.expr.callee.endswith("_create"):
                        c_type = stmt.expr.callee[:-7]
                    elif stmt.expr.callee in self.functions:
                        c_type = self._c_type(self.functions[stmt.expr.callee].return_type)
                    else:
                        c_type = "int"
                else:
                    c_type = "int"
            lines.append(f"{indent}{c_type} {stmt.name} = {expr_code};")
            ctx["vars"][stmt.name] = c_type

        elif isinstance(stmt, AssignStmt):
            expr_code, pre_stmts = self._gen_expr(stmt.expr, ctx, indent)
            for p in pre_stmts:
                lines.append(f"{indent}{p}" if not p.startswith(indent) else p)

            if isinstance(stmt.target, FieldAccess):
                obj = stmt.target.obj
                fld = stmt.target.field
                # Check if obj is an active loop proxy
                loop_info = next((l for l in ctx["active_loops"] if l["loop_var"] == obj), None)
                if loop_info:
                    table_name = loop_info["table_name"]
                    idx_var = loop_info["idx_var"]
                    is_ptr = loop_info["is_ptr"]
                    arrow = "->" if is_ptr else "."
                    target_code = f"{table_name}{arrow}{fld}[{idx_var}]"
                else:
                    target_code = f"{obj}.{fld}"
            else:
                target_code = stmt.target.name

            lines.append(f"{indent}{target_code} {stmt.op} {expr_code};")

        elif isinstance(stmt, ForStmt):
            # Table iteration lowering to SIMD vectorizable loop
            is_ptr = False
            param = ctx["params"].get(stmt.iter_target)
            if param and param.type_node and param.type_node.is_table and param.intent in {"mut", "let"}:
                is_ptr = True

            arrow = "->" if is_ptr else "."
            idx_var = f"__{stmt.loop_var}_idx"
            count_expr = f"{stmt.iter_target}{arrow}count"

            loop_ctx = {
                "loop_var": stmt.loop_var,
                "table_name": stmt.iter_target,
                "idx_var": idx_var,
                "is_ptr": is_ptr
            }
            ctx["active_loops"].append(loop_ctx)

            lines.append(f"{indent}AETHER_SIMD_LOOP")
            lines.append(f"{indent}for (size_t {idx_var} = 0; {idx_var} < {count_expr}; ++{idx_var}) {{")
            for s in stmt.body:
                lines.extend(self._gen_stmt(s, ctx, indent + "    "))
            lines.append(f"{indent}}}")

            ctx["active_loops"].pop()

        elif isinstance(stmt, ReturnStmt):
            if stmt.expr:
                expr_code, pre_stmts = self._gen_expr(stmt.expr, ctx, indent)
                lines.extend(pre_stmts)
                lines.append(f"{indent}return {expr_code};")
            else:
                lines.append(f"{indent}return;")

        elif isinstance(stmt, ExprStmt):
            if stmt.expr:
                expr_code, pre_stmts = self._gen_expr(stmt.expr, ctx, indent)
                lines.extend(pre_stmts)
                lines.append(f"{indent}{expr_code};")

        return lines

    def _gen_expr(self, expr: Expr, ctx: dict, indent: str) -> (str, List[str]):
        pre_stmts = []

        if isinstance(expr, NumberLiteral):
            val = expr.value
            if expr.is_float and not val.endswith("f") and not val.endswith("F"):
                val += "f"
            return val, pre_stmts

        if isinstance(expr, Identifier):
            return expr.name, pre_stmts

        if isinstance(expr, FieldAccess):
            obj = expr.obj
            fld = expr.field
            loop_info = next((l for l in ctx["active_loops"] if l["loop_var"] == obj), None)
            if loop_info:
                table_name = loop_info["table_name"]
                idx_var = loop_info["idx_var"]
                is_ptr = loop_info["is_ptr"]
                arrow = "->" if is_ptr else "."
                return f"{table_name}{arrow}{fld}[{idx_var}]", pre_stmts
            return f"{obj}.{fld}", pre_stmts

        if isinstance(expr, BinaryExpr):
            l_code, l_pre = self._gen_expr(expr.left, ctx, indent)
            r_code, r_pre = self._gen_expr(expr.right, ctx, indent)
            pre_stmts.extend(l_pre)
            pre_stmts.extend(r_pre)
            if expr.op == "+%":
                return f"aether_add_wrap_i32({l_code}, {r_code})", pre_stmts
            elif expr.op == "+!":
                return f"aether_add_sat_i32({l_code}, {r_code})", pre_stmts
            return f"({l_code} {expr.op} {r_code})", pre_stmts

        if isinstance(expr, CallExpr):
            arg_strs = []
            for intent, arg in expr.args:
                acode, apre = self._gen_expr(arg, ctx, indent)
                pre_stmts.extend(apre)
                # If passing a Table with mut intent to a mut parameter, pass its address
                if intent == "mut":
                    acode = f"&{acode}"
                arg_strs.append(acode)
            return f"{expr.callee}({', '.join(arg_strs)})", pre_stmts

        if isinstance(expr, MethodCallExpr):
            if expr.method == "join":
                target_ret = ctx.get("ret_type", "void*")
                return f"*({target_ret}*)aether_join({expr.obj})", pre_stmts
            return f"{expr.obj}.{expr.method}()", pre_stmts

        if isinstance(expr, SpawnExpr):
            self.task_counter += 1
            task_name = f"__aether_fiber_{self.task_counter}"
            arg_struct_name = f"__Aether_TaskArgs_{self.task_counter}"

            # Discover captured variables in spawn body
            captured = []
            for s in expr.body:
                if isinstance(s, ExprStmt) and isinstance(s.expr, CallExpr):
                    for intent, a in s.expr.args:
                        if isinstance(a, Identifier) and a.name in ctx["params"]:
                            p = ctx["params"][a.name]
                            captured.append((p.name, self._c_type(p.type_node)))
                elif isinstance(s, ReturnStmt) and isinstance(s.expr, Identifier):
                    if s.expr.name in ctx["params"]:
                        p = ctx["params"][s.expr.name]
                        if not any(c[0] == p.name for c in captured):
                            captured.append((p.name, self._c_type(p.type_node)))

            # Generate task argument structure
            task_lines = [
                f"typedef struct {arg_struct_name} {{",
            ]
            for cname, ctype in captured:
                task_lines.append(f"    {ctype} {cname};")
            # Result field
            task_lines.append(f"    void* result_ptr;")
            task_lines.append(f"}} {arg_struct_name};")
            task_lines.append("")

            # Generate task entry function
            task_lines.append(f"static void* {task_name}(void* __raw_arg) {{")
            task_lines.append(f"    {arg_struct_name}* __args = ({arg_struct_name}*)__raw_arg;")
            for cname, ctype in captured:
                task_lines.append(f"    {ctype} {cname} = __args->{cname};")

            sub_ctx = {
                "params": {cname: Param(0, 0, cname, None, "owned") for cname, ctype in captured},
                "vars": {},
                "active_loops": []
            }

            for s in expr.body:
                if isinstance(s, ReturnStmt) and s.expr:
                    ret_code, rpre = self._gen_expr(s.expr, sub_ctx, "    ")
                    for p in rpre:
                        task_lines.append(p)
                    # Allocate heap box for result to return across fiber boundary
                    ret_type = captured[0][1] if captured else "void*"
                    task_lines.append(f"    {ret_type}* __res = ({ret_type}*)malloc(sizeof({ret_type}));")
                    task_lines.append(f"    *__res = {ret_code};")
                    task_lines.append(f"    return (void*)__res;")
                else:
                    task_lines.extend(self._gen_stmt(s, sub_ctx, "    "))
            task_lines.append("    return NULL;")
            task_lines.append("}")
            task_lines.append("")

            self.helper_defs.extend(task_lines)

            # In caller: allocate args and call aether_spawn
            pre_stmts.append(f"{arg_struct_name}* __targs_{self.task_counter} = ({arg_struct_name}*)malloc(sizeof({arg_struct_name}));")
            for cname, ctype in captured:
                pre_stmts.append(f"__targs_{self.task_counter}->{cname} = {cname};")

            return f"aether_spawn({task_name}, __targs_{self.task_counter})", pre_stmts

        return "/* unknown expr */", pre_stmts
